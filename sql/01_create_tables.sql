
-- =====================================================
-- IPL PLAYER PERFORMANCE DASHBOARD
-- Oracle Database 26ai Free
-- Schema: IPL_USER
-- =====================================================

-- 1. MATCHES TABLE
CREATE TABLE MATCHES (
    ID NUMBER(10) PRIMARY KEY,
    SEASON VARCHAR2(10),
    CITY VARCHAR2(100),
    MATCH_DATE DATE,
    MATCH_TYPE VARCHAR2(50),
    PLAYER_OF_MATCH VARCHAR2(100),
    VENUE VARCHAR2(200),
    TEAM1 VARCHAR2(100),
    TEAM2 VARCHAR2(100),
    TOSS_WINNER VARCHAR2(100),
    TOSS_DECISION VARCHAR2(20),
    WINNER VARCHAR2(100),
    RESULT VARCHAR2(30),
    RESULT_MARGIN NUMBER(10,2),
    TARGET_RUNS NUMBER(10,2),
    TARGET_OVERS NUMBER(5,2),
    SUPER_OVER VARCHAR2(5),
    METHOD VARCHAR2(50),
    UMPIRE1 VARCHAR2(100),
    UMPIRE2 VARCHAR2(100)
);

-- 2. DELIVERIES TABLE
CREATE TABLE DELIVERIES (
    MATCH_ID NUMBER(10),
    INNING NUMBER(2),
    BATTING_TEAM VARCHAR2(100),
    BOWLING_TEAM VARCHAR2(100),
    OVER_NUMBER NUMBER(2),
    BALL_NUMBER NUMBER(3),
    BATTER VARCHAR2(100),
    BOWLER VARCHAR2(100),
    NON_STRIKER VARCHAR2(100),
    BATSMAN_RUNS NUMBER(3),
    EXTRA_RUNS NUMBER(3),
    TOTAL_RUNS NUMBER(3),
    EXTRAS_TYPE VARCHAR2(30),
    IS_WICKET NUMBER(1),
    PLAYER_DISMISSED VARCHAR2(100),
    DISMISSAL_KIND VARCHAR2(50),
    FIELDER VARCHAR2(100),
    INNINGS_ID VARCHAR2(30),
    BOWLER_RUNS NUMBER(3),
    LEGAL_BALL NUMBER(1),

    CONSTRAINT FK_DEL_MATCH
        FOREIGN KEY (MATCH_ID) REFERENCES MATCHES(ID)
);

-- 3. ALL-TIME BATTING STATS
CREATE TABLE BATTING_STATS (
    BATTER VARCHAR2(100) PRIMARY KEY,
    INNINGS NUMBER(5),
    RUNS NUMBER(10),
    BALLS_FACED NUMBER(10),
    DISMISSALS NUMBER(10),
    BATTING_AVERAGE NUMBER(10,2),
    STRIKE_RATE NUMBER(10,2)
);

-- 4. ALL-TIME BOWLING STATS
CREATE TABLE BOWLING_STATS (
    BOWLER VARCHAR2(100) PRIMARY KEY,
    INNINGS NUMBER(5),
    RUNS_CONCEDED NUMBER(10),
    BALLS_BOWLED NUMBER(10),
    WICKETS NUMBER(5),
    OVERS NUMBER(10,1),
    ECONOMY NUMBER(10,2),
    BOWLING_AVERAGE NUMBER(10,2),
    BOWLING_STRIKE_RATE NUMBER(10,2)
);

-- 5. SEASON-WISE BATTING STATS
CREATE TABLE SEASON_BATTING_STATS (
    SEASON VARCHAR2(10),
    BATTER VARCHAR2(100),
    RUNS NUMBER(10),
    BALLS_FACED NUMBER(10),
    INNINGS NUMBER(5),
    DISMISSALS NUMBER(5),
    AVERAGE NUMBER(10,2),
    STRIKE_RATE NUMBER(10,2),

    CONSTRAINT PK_SEASON_BATTING
        PRIMARY KEY (SEASON, BATTER)
);

-- 6. SEASON-WISE BOWLING STATS
CREATE TABLE SEASON_BOWLING_STATS (
    SEASON VARCHAR2(10),
    BOWLER VARCHAR2(100),
    INNINGS NUMBER(5),
    RUNS_CONCEDED NUMBER(10),
    BALLS_BOWLED NUMBER(10),
    WICKETS NUMBER(5),
    OVERS NUMBER(10,1),
    ECONOMY NUMBER(10,2),
    BOWLING_AVERAGE NUMBER(10,2),
    BOWLING_STRIKE_RATE NUMBER(10,2),

    CONSTRAINT PK_SEASON_BOWLING
        PRIMARY KEY (SEASON, BOWLER)
);

-- Useful indexes for analysis
CREATE INDEX IDX_DEL_MATCH ON DELIVERIES(MATCH_ID);
CREATE INDEX IDX_DEL_BATTER ON DELIVERIES(BATTER);
CREATE INDEX IDX_DEL_BOWLER ON DELIVERIES(BOWLER);
CREATE INDEX IDX_MATCH_SEASON ON MATCHES(SEASON);
