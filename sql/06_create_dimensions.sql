-- IPL PLAYER PERFORMANCE DASHBOARD
-- DIMENSION VIEWS FOR STAR SCHEMA
-- =====================================================

-- 1. PLAYER DIMENSION
CREATE OR REPLACE VIEW VW_DIM_PLAYER AS
SELECT
    PLAYER_NAME,
    MAX(IS_BATTER) AS IS_BATTER,
    MAX(IS_BOWLER) AS IS_BOWLER
FROM (
    SELECT
        BATTER AS PLAYER_NAME,
        1 AS IS_BATTER,
        0 AS IS_BOWLER
    FROM BATTING_STATS

    UNION ALL

    SELECT
        BOWLER AS PLAYER_NAME,
        0 AS IS_BATTER,
        1 AS IS_BOWLER
    FROM BOWLING_STATS
)
GROUP BY PLAYER_NAME;


-- 2. TEAM DIMENSION
CREATE OR REPLACE VIEW VW_DIM_TEAM AS
SELECT TEAM_NAME
FROM (
    SELECT TEAM1 AS TEAM_NAME FROM MATCHES
    UNION
    SELECT TEAM2 FROM MATCHES
    UNION
    SELECT WINNER FROM MATCHES
    WHERE WINNER IS NOT NULL
);


-- 3. SEASON DIMENSION
CREATE OR REPLACE VIEW VW_DIM_SEASON AS
SELECT DISTINCT SEASON
FROM MATCHES;


-- 4. VENUE DIMENSION
CREATE OR REPLACE VIEW VW_DIM_VENUE AS
SELECT
    VENUE,
    MAX(CITY) AS CITY
FROM MATCHES
WHERE VENUE IS NOT NULL
GROUP BY VENUE;


-- 5. DATE DIMENSION
CREATE OR REPLACE VIEW VW_DIM_DATE AS
SELECT DISTINCT
    MATCH_DATE,
    EXTRACT(YEAR FROM MATCH_DATE) AS YEAR_NUMBER,
    EXTRACT(MONTH FROM MATCH_DATE) AS MONTH_NUMBER,
    TO_CHAR(MATCH_DATE, 'Month') AS MONTH_NAME,
    TO_CHAR(MATCH_DATE, 'Q') AS QUARTER_NUMBER
FROM MATCHES
WHERE MATCH_DATE IS NOT NULL;

