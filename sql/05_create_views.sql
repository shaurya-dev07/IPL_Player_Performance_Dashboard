CREATE OR REPLACE VIEW VW_PLAYER_BATTING AS
SELECT
    BATTER,
    INNINGS,
    RUNS,
    BALLS_FACED,
    DISMISSALS,
    BATTING_AVERAGE,
    STRIKE_RATE
FROM BATTING_STATS;

CREATE OR REPLACE VIEW VW_PLAYER_BOWLING AS
SELECT
    BOWLER,
    INNINGS,
    RUNS_CONCEDED,
    BALLS_BOWLED,
    WICKETS,
    OVERS,
    ECONOMY,
    BOWLING_AVERAGE,
    BOWLING_STRIKE_RATE
FROM BOWLING_STATS;

CREATE OR REPLACE VIEW VW_SEASON_BATTING AS
SELECT *
FROM SEASON_BATTING_STATS;

CREATE OR REPLACE VIEW VW_SEASON_BOWLING AS
SELECT *
FROM SEASON_BOWLING_STATS;

-- Combines batting and bowling records
CREATE OR REPLACE VIEW VW_PLAYER_COMPARISON AS
SELECT
    NVL(B.BATTER, BW.BOWLER) AS PLAYER_NAME,
    B.INNINGS AS BATTING_INNINGS,
    B.RUNS,
    B.BATTING_AVERAGE,
    B.STRIKE_RATE,
    BW.INNINGS AS BOWLING_INNINGS,
    BW.WICKETS,
    BW.ECONOMY,
    BW.BOWLING_AVERAGE,
    BW.BOWLING_STRIKE_RATE
FROM BATTING_STATS B
FULL OUTER JOIN BOWLING_STATS BW
    ON B.BATTER = BW.BOWLER;

-- Match details
CREATE OR REPLACE VIEW VW_MATCH_RESULTS AS
SELECT
    ID AS MATCH_ID,
    SEASON,
    MATCH_DATE,
    CITY,
    VENUE,
    TEAM1,
    TEAM2,
    WINNER,
    RESULT,
    RESULT_MARGIN,
    PLAYER_OF_MATCH
FROM MATCHES;

-- Total wins by team
CREATE OR REPLACE VIEW VW_TEAM_WINS AS
SELECT
    WINNER AS TEAM_NAME,
    COUNT(*) AS TOTAL_WINS
FROM MATCHES
WHERE WINNER IS NOT NULL
GROUP BY WINNER;

-- Total runs and active batters per season
CREATE OR REPLACE VIEW VW_SEASON_RUNS AS
SELECT
    M.SEASON,
    SUM(D.TOTAL_RUNS) AS TOTAL_RUNS,
    COUNT(DISTINCT D.BATTER) AS ACTIVE_BATTERS
FROM DELIVERIES D
JOIN MATCHES M
    ON D.MATCH_ID = M.ID
GROUP BY M.SEASON;

-- Match count per season
CREATE OR REPLACE VIEW VW_SEASON_MATCH_COUNTS AS
SELECT
    SEASON,
    COUNT(*) AS MATCHES_PLAYED
FROM MATCHES
GROUP BY SEASON;

